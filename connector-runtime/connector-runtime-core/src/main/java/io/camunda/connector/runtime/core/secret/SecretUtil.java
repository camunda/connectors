package io.camunda.connector.runtime.core.secret;

import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.function.Function;
import java.util.regex.MatchResult;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/** Utility class to replace secrets in strings. */
public class SecretUtil {

  private static final Pattern SECRET_PATTERN_SECRETS =
      Pattern.compile("secrets\\.(?<secret>([a-zA-Z0-9]+[\\/._-])*[a-zA-Z0-9]+)");

  private static final Pattern SECRET_PATTERN_PARENTHESES =
      Pattern.compile("\\{\\{\\s*secrets\\.(?<secret>\\S+?\\s*)}}");

  // The exact character class SECRET_PATTERN_SECRETS captures. A bracketed name outside it (e.g.
  // containing ':') is truncated by the bare pattern's own narrower match -- see
  // replaceSecretsWithoutParentheses below.
  private static final Pattern BARE_SECRET_NAME =
      Pattern.compile("([a-zA-Z0-9]+[\\/._-])*[a-zA-Z0-9]+");

  public static String replaceSecrets(String input, Function<String, String> secretReplacer) {
    if (input == null) {
      throw new IllegalStateException("input cant be null.");
    }
    // Shared across both passes so that a name resolved (or denied) while scanning brackets is
    // never looked up again for the bare-pass denial check below -- secretReplacer is not
    // guaranteed side-effect-free in production (a provider aggregator can count each resolution),
    // so a name must be asked for at most once per call, whichever pass asks first.
    Map<String, String> resolutionsByName = new HashMap<>();
    input = replaceSecretsWithParentheses(input, secretReplacer, resolutionsByName);
    input = replaceSecretsWithoutParentheses(input, secretReplacer, resolutionsByName);
    return input;
  }

  private static String replaceSecretsWithParentheses(
      String input,
      Function<String, String> secretReplacer,
      Map<String, String> resolutionsByName) {
    var secretVariableNameWithParenthesesMatcher = SECRET_PATTERN_PARENTHESES.matcher(input);
    while (secretVariableNameWithParenthesesMatcher.find()) {
      input =
          replaceTokens(
              input,
              SECRET_PATTERN_PARENTHESES,
              matcher -> resolveSecretValue(secretReplacer, matcher, resolutionsByName));
    }
    return input;
  }

  /**
   * A bracketed reference still present in the text at this point -- whether from the original
   * input or generated by a chained resolution above -- has its own full name. When that name
   * contains a character the bare pattern's narrower class does not (e.g. {@code :}), the bare
   * pattern would only ever match a truncated prefix of it: a different name than the bracket
   * declares. Resolving that prefix independently either discards a successful full-name
   * resolution's actual value in favor of the prefix's own, or bypasses a denial of the full name
   * via an allowed prefix. Such a bracket is resolved by its own full name directly, consuming the
   * whole bracketed span, before the bare pattern ever touches it. A bracket whose full name is
   * entirely bare-pattern-safe needs none of this: resolving the (identical) bare match already
   * gives the correct result, so it is left for the scan below.
   */
  private static String replaceSecretsWithoutParentheses(
      String input,
      Function<String, String> secretReplacer,
      Map<String, String> resolutionsByName) {
    var secretVariableNameWithParenthesesMatcher = SECRET_PATTERN_SECRETS.matcher(input);
    while (secretVariableNameWithParenthesesMatcher.find()) {
      input =
          replaceTokens(
              input,
              SECRET_PATTERN_PARENTHESES,
              matcher ->
                  isTruncatedByBarePattern(matcher)
                      ? resolveSecretValue(secretReplacer, matcher, resolutionsByName)
                      : matcher.group());

      List<MatchResult> deniedBracketedReferences =
          SECRET_PATTERN_PARENTHESES
              .matcher(input)
              .results()
              .filter(
                  match ->
                      isTruncatedByBarePattern(match)
                          && isDenied(match, secretReplacer, resolutionsByName))
              .toList();
      input =
          replaceTokens(
              input,
              SECRET_PATTERN_SECRETS,
              matcher ->
                  isNotNestedInAny(matcher, deniedBracketedReferences)
                      ? resolveSecretValue(secretReplacer, matcher, resolutionsByName)
                      : matcher.group());
    }
    return input;
  }

  private static boolean isTruncatedByBarePattern(MatchResult bracketedMatch) {
    String name = bracketedMatch.group("secret").trim();
    return !BARE_SECRET_NAME.matcher(name).matches();
  }

  private static boolean isDenied(
      MatchResult bracketedMatch,
      Function<String, String> secretReplacer,
      Map<String, String> resolutionsByName) {
    String name = bracketedMatch.group("secret").trim();
    return resolve(name, secretReplacer, resolutionsByName) == null;
  }

  private static String resolveSecretValue(
      Function<String, String> secretReplacer,
      Matcher matcher,
      Map<String, String> resolutionsByName) {
    var secretName = matcher.group("secret").trim();
    if (!secretName.isBlank() && !secretName.isEmpty()) {
      var result = resolve(secretName, secretReplacer, resolutionsByName);
      if (result != null) {
        return result;
      } else {
        return matcher.group();
      }
    } else {
      return null;
    }
  }

  // A plain computeIfAbsent would re-invoke secretReplacer for every denied name (Map treats a
  // null result as "still absent"), defeating the memoization this exists for.
  private static String resolve(
      String name, Function<String, String> secretReplacer, Map<String, String> resolutionsByName) {
    if (resolutionsByName.containsKey(name)) {
      return resolutionsByName.get(name);
    }
    String result = secretReplacer.apply(name);
    resolutionsByName.put(name, result);
    return result;
  }

  public static List<String> retrieveSecretKeysInInput(String input) {
    if (Objects.isNull(input)) {
      return List.of();
    }
    List<MatchResult> bracketedReferences =
        SECRET_PATTERN_PARENTHESES.matcher(input).results().toList();
    return Stream.of(SECRET_PATTERN_PARENTHESES, SECRET_PATTERN_SECRETS)
        .flatMap(
            pattern ->
                pattern
                    .matcher(input)
                    .results()
                    .filter(
                        result ->
                            pattern != SECRET_PATTERN_SECRETS
                                || isNotNestedInAny(result, bracketedReferences)))
        .map(matchResult -> matchResult.group("secret").trim())
        .distinct()
        .toList();
  }

  /**
   * A bare {@code secrets.NAME} match nested inside a {@code {{secrets.NAME}}} occurrence is not a
   * second, independent declaration — it is the bare pattern's narrower character class re-reading
   * the same literal text and stopping short at a character the bracket form tolerates (e.g. {@code
   * :}). Left in, a model declaring only {@code {{secrets.LONG:SUFFIX}}} would also admit the
   * truncated "LONG" into the allow-list, letting a runtime value spell that shorter name and
   * resolve a secret the model never declared.
   */
  private static boolean isNotNestedInAny(MatchResult candidate, List<MatchResult> outerMatches) {
    return outerMatches.stream()
        .noneMatch(outer -> candidate.start() >= outer.start() && candidate.end() <= outer.end());
  }

  public static String replaceTokens(
      String original, Pattern pattern, Function<Matcher, String> converter) {
    int lastIndex = 0;
    StringBuilder output = new StringBuilder();
    Matcher matcher = pattern.matcher(original);
    while (matcher.find()) {
      output.append(original, lastIndex, matcher.start()).append(converter.apply(matcher));
      lastIndex = matcher.end();
    }
    if (lastIndex < original.length()) {
      output.append(original, lastIndex, original.length());
    }
    return output.toString();
  }
}
